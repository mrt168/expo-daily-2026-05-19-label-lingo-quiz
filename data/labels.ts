// 全英単語から不正解候補（ja）を集めるためのプール
export const distractorPool: string[] = labels
  .flatMap((l) => l.words.map((w) => w.ja))
  .filter((v, i, a) => a.indexOf(v) === i);

export function getTodayLabel(dateStr: string, isFirstTime: boolean): Label {
  if (isFirstTime) {
    // 初回起動時は必ず "starter" を返す
    return labels[0];
  }
  // 日付ベースで決定論的に選ぶ
  const seed = Array.from(dateStr).reduce((s, c) => s + c.charCodeAt(0), 0);
  const idx = seed % labels.length;
  return labels[idx];
}

export function getLabelById(id: string): Label | undefined {
  return labels.find((l) => l.id === id);
}
